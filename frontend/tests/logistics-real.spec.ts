import { expect, test, type Page } from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const evidence = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../docs/assets/logistics')
fs.mkdirSync(evidence, { recursive: true })
const nav = (page: Page, name: string) => page.locator(`[data-test="nav-${name}"]`)

async function enter(page: Page, username = 'logistics') {
  await page.goto('logistics')
  await page.getByLabel('用户名', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill('Logistics!2026')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/app\/logistics$/)
  await expect(page.getByRole('heading', { name: '物流协同工作台' })).toBeVisible()
  await expect(page.locator('.metrics-grid')).toBeVisible()
}

function beijingInput(date: Date) {
  return new Date(date.getTime() + 8 * 3_600_000).toISOString().slice(0, 19)
}

