  await page.screenshot({ path: path.join(evidence, 'agent-evidence.png'), fullPage: true })
  await nav(page, 'exceptions').click()
  const card = page.locator('.exception-card').filter({ has: page.getByRole('button', { name: '分配工单', exact: true }) }).first()
